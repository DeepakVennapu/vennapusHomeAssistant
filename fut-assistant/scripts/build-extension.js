// Bundles the solver (src/*.js, ES modules) into one plain script the extension can load
// in the Web App page, where ES module imports aren't available.
//   node scripts/build-extension.js          writes extension/solver-bundle.js
//   node scripts/build-extension.js --check  fails if the bundle is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ORDER = ['model.js', 'rating.js', 'chemistry.js', 'requirements.js', 'solver.js', 'analyze.js'];
const src = (f) => fileURLToPath(new URL(`../src/${f}`, import.meta.url));
const out = fileURLToPath(new URL('../extension/solver-bundle.js', import.meta.url));

export function buildBundle() {
  const parts = ORDER.map((f) => {
    const code = readFileSync(src(f), 'utf8')
      .replace(/^import .*;\n/gm, '')
      .replace(/^export (?=(const|function|let|class) )/gm, '');
    if (/^\s*(import|export)\b/m.test(code)) throw new Error(`${f}: unsupported import/export form`);
    return `  // ---- src/${f} ----\n${code.replace(/^(?=.)/gm, '  ')}`;
  });
  return `// GENERATED by scripts/build-extension.js from src/. Do not edit; run \`npm run build\`.
(() => {
  'use strict';
${parts.join('\n')}
  window.__futAssistantSolver = { normalizeClub, normalizePlayer, solve, analyzeRepeat, evaluate };
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bundle = buildBundle();
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8');
    if (current !== bundle) { console.error('extension/solver-bundle.js is out of date. Run: npm run build'); process.exit(1); }
    console.log('Bundle is up to date.');
  } else {
    writeFileSync(out, bundle);
    console.log(`Wrote ${out}`);
  }
}
